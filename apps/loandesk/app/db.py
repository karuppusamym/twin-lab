"""SQLite access. The file comes from DATABASE_URL (sqlite:///<path>); tables from db/schema.sql."""

from __future__ import annotations

import logging
import os
import re
import sqlite3
import threading
import time
from contextlib import contextmanager
from pathlib import Path

log = logging.getLogger("loandesk.db")

SCHEMA_PATH = Path(
    os.environ.get(
        "LOANDESK_SCHEMA_PATH", Path(__file__).resolve().parent.parent / "db" / "schema.sql"
    )
)
BUSY_TIMEOUT_S = 30


def database_path() -> str:
    url = os.environ.get("DATABASE_URL", "")
    if url.startswith("sqlite:///"):
        return url[len("sqlite:///") :]  # sqlite:////abs/path -> /abs/path
    return os.environ.get("DB_PATH", "") or _fail()


def _fail() -> str:
    raise RuntimeError("DATABASE_URL (sqlite:///<path>) is not set")


@contextmanager
def connect():
    conn = sqlite3.connect(database_path(), timeout=BUSY_TIMEOUT_S)
    conn.row_factory = sqlite3.Row
    conn.execute(f"PRAGMA busy_timeout = {BUSY_TIMEOUT_S * 1000}")
    conn.execute("PRAGMA foreign_keys = ON")
    try:
        yield conn
        conn.commit()
    except BaseException:
        conn.rollback()
        raise
    finally:
        conn.close()


def ping() -> bool:
    try:
        with connect() as conn:
            conn.execute("SELECT 1 FROM users LIMIT 1")
        return True
    except Exception:  # noqa: BLE001 - any failure means "database not usable"
        return False


def sqlite_ddl(postgres_sql: str) -> str:
    """db/schema.sql is written for Postgres; SQLite needs the identity clause dropped.

    `INTEGER ... PRIMARY KEY (col)` makes the column the rowid, so it still auto-increments.
    Statements are made idempotent so tables the lab already created are left alone.
    """
    sql = postgres_sql.replace(" GENERATED BY DEFAULT AS IDENTITY", "")
    sql = re.sub(r"\bBIGINT\b", "INTEGER", sql)
    sql = sql.replace("CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ")
    sql = sql.replace("CREATE INDEX ", "CREATE INDEX IF NOT EXISTS ")
    return sql


def ensure_schema(conn) -> None:
    conn.executescript(sqlite_ddl(SCHEMA_PATH.read_text(encoding="utf-8")))


def initialise() -> None:
    """Create missing tables and the synthetic seed, retrying until the file is usable."""
    from app import seed

    delay = 1.0
    while True:
        try:
            with connect() as conn:
                ensure_schema(conn)
            with connect() as conn:
                conn.execute("BEGIN IMMEDIATE")
                if seed.seed_if_empty(conn):
                    log.info("loaded synthetic seed data")
            return
        except Exception as exc:  # noqa: BLE001 - keep trying; the lab may still be preparing it
            log.warning("database not ready yet: %s", exc)
            time.sleep(delay)
            delay = min(delay * 2, 10.0)


def start_initialiser() -> None:
    threading.Thread(target=initialise, name="loandesk-db-init", daemon=True).start()
