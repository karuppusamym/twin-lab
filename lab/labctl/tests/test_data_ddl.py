# --- SQLite, oddities, never crashing ----------------------------------------------------------


def test_sqlite_and_composite_keys():
    text = """
    CREATE TABLE IF NOT EXISTS "tag" (id INTEGER PRIMARY KEY AUTOINCREMENT, label TEXT NOT NULL UNIQUE);
    CREATE TABLE post (id INTEGER PRIMARY KEY, title VARCHAR(80), parent_id INTEGER REFERENCES post);
    CREATE TABLE post_tag (
      post_id INTEGER NOT NULL REFERENCES post(id),
      tag_id INTEGER NOT NULL REFERENCES "tag"(id),
      weight,
      PRIMARY KEY (post_id, tag_id),
      UNIQUE (tag_id, weight)
    );
    """  # noqa: E501
    tables, problems = ddl.parse_with_problems(text)
    tag, post, link = cols(tables, "tag"), cols(tables, "post"), cols(tables, "post_tag")
    assert tag["id"].autoincrement and tag["label"].unique
    assert post["id"].autoincrement  # INTEGER PRIMARY KEY is the SQLite row id
    assert post["parent_id"].references == ("post", "id")  # REFERENCES without a column
    assert link["post_id"].primary_key and link["tag_id"].primary_key
    assert not link["post_id"].autoincrement
    assert link["weight"].type == "TEXT"
    assert not link["tag_id"].unique
    text = "\n".join(problems)
    assert "post_tag.weight: no type given" in text
    assert "unique key on (tag_id, weight) is not checked" in text


def test_unknown_statements_and_garbage_never_crash():
    text = """
    CREATE TABLE ok (id INT PRIMARY KEY, shape GEOMETRY, span INTERVAL);
    MERGE INTO ok USING x ON (1=1);
    FROBNICATE everything;
    CREATE TABLE broken (id int, name varchar(10);
    CREATE TABLE copy_of AS SELECT * FROM ok;
    ALTER TABLE missing ADD CONSTRAINT fk FOREIGN KEY (a) REFERENCES ok(id);
    ALTER TABLE ok ADD CONSTRAINT fk2 FOREIGN KEY (nope) REFERENCES ok(id);
    CREATE TABLE child (ok_id INT REFERENCES elsewhere(id));
    ))) ;;; '
    """
    tables, problems = ddl.parse_with_problems(text)
    assert [t.name for t in tables] == ["ok", "child"]
    ok = cols(tables, "ok")
    assert ok["shape"].type == "TEXT" and ok["span"].type == "TEXT"
    text = "\n".join(problems)
    for expected in [
        "ok.shape: type GEOMETRY not recognised",
        "FROBNICATE everything not understood",
        "brackets do not balance",
        "table copy_of has no column list",
        "ALTER TABLE missing: table not defined before it",
        "FOREIGN names column nope, which is not defined",
        "child.ok_id refers to table elsewhere, which is not in this file",
        "1 statement(s) with rows",
    ]:
        assert expected in text, (expected, problems)
    assert all(p.startswith("line ") or "statement(s)" in p for p in problems)
    assert ddl.parse("") == []
    assert ddl.parse("-- nothing here\n/* at all */") == []


def test_problems_name_the_line():
    _, problems = ddl.parse_with_problems("CREATE TABLE a (id int);\n\nCREATE VIEW v AS SELECT 1;")
    assert problems == ["line 3: skipped: CREATE VIEW v (only tables are read)"]


def test_to_model():
    model = ddl.to_model("showcase", SHOWCASE.read_text(encoding="utf-8"), "ddl:showcase-schema")
    assert isinstance(model, AppModel)
    assert model.evidence[0].kind == "ddl" and model.evidence[0].complete == ["tables"]
    assert model.evidence[0].ref.startswith("sha256:")
    assert model.complete("tables") == ["ddl:showcase-schema"]
    cases = model.table("cases")
    assert cases.basis == "declared" and cases.from_ == ["ddl:showcase-schema"]
    assert next(c for c in cases.columns if c.name == "customer_id").references == [
        "customer", "id"
    ]  # fmt: skip
    dumped = model.model_dump(mode="json", by_alias=True)
    assert AppModel.model_validate(dumped) == model
