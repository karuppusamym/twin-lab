MODELS = ROOT / "reference" / "case-workbench" / "backend" / "app" / "models.py"


def cols(tables, name):
    table = next(t for t in tables if t.name == name)
    return {c.name: c for c in table.columns}


def shape(tables):
    return {
        t.name: [
            (c.name, c.type, c.nullable, c.primary_key, c.unique, c.references, c.autoincrement)
            for c in t.columns
        ]
        for t in tables
    }


