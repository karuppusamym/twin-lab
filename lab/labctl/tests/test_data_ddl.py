def test_showcase_schema_reads_back_as_written():
    tables, problems = ddl.parse_with_problems(SHOWCASE.read_text(encoding="utf-8"))
    assert problems == []
    assert [t.name for t in tables] == [
        "app_user", "customer", "category", "subcategory", "cases", "case_note", "case_audit"
    ]  # fmt: skip
    cases = cols(tables, "cases")
    assert cases["id"].autoincrement and cases["id"].primary_key and not cases["id"].nullable
    assert cases["case_no"].type == "VARCHAR(12)" and cases["case_no"].unique
    assert cases["category_id"].nullable and cases["category_id"].references == ("category", "id")
    assert cases["opened_at"].type == "TIMESTAMP WITH TIME ZONE"
    assert cases["status"].index
    assert cols(tables, "customer")["full_name"].index


@pytest.mark.parametrize("engine", sam.ENGINES)
def test_every_dialect_labctl_writes_round_trips(engine):
    source, _ = sam.parse(MODELS)
    header = f"Generated for a test.\nDialect: {engine}. Table and column names must not change."
    text = sam.ddl(source, header, engine)
    tables, problems = ddl.parse_with_problems(text)
    assert problems == []
    want = shape(sam.ordered(source))
    got = shape(tables)
    if engine == "mysql":  # MySQL has no time zone type: DATETIME(6) reads back as TIMESTAMP
        want = {
            t: [(c[0], "TIMESTAMP" if c[1] == "TIMESTAMP WITH TIME ZONE" else c[1], *c[2:])
                for c in cs]
            for t, cs in want.items()
        }  # fmt: skip
    if engine == "sqlite":  # SQLite numbers only an INTEGER primary key
        want = {t: [(*c[:6], c[6] and c[1] == "INTEGER") for c in cs] for t, cs in want.items()}
    assert got == want


