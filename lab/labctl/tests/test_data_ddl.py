    assert account["created_at"].type == "TIMESTAMP WITH TIME ZONE"
    assert account["seen"].type == "TIMESTAMP"
    assert account["prefs"].type == "JSON"
    assert account["token"].type == "UUID"
    assert account["photo"].type == "BLOB"
    assert account["rating"].type == "DOUBLE PRECISION"
    assert account["tags"].type == "TEXT"
    ticket = cols(tables, "ticket")
    assert ticket["id"].type == "BIGINT" and ticket["id"].autoincrement and ticket["id"].primary_key
    assert ticket["state"].type == "VARCHAR(8)"  # the enum's longest label
