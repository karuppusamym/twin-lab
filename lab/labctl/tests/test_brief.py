def test_legacy_column_style_and_cycles(tmp_path):
    src = tmp_path / "m.py"
    src.write_text(
        "from sqlalchemy import Column, Integer, Numeric, ForeignKey\n"
        "class A(Base):\n    __tablename__ = 'a'\n    id = Column(Integer, primary_key=True)\n"
        "    b_id = Column(Integer, ForeignKey('b.id'), nullable=False)\n"
        "    amount = Column(Numeric(12, 2))\n"
        "class B(Base):\n    __tablename__ = 'b'\n    id = Column(Integer, primary_key=True)\n"
        "    a_id = Column(Integer, ForeignKey('a.id'))\n",
        encoding="utf-8",
    )
    tables, problems = sam.parse(src)
    assert problems == []
    a = tables[0]
    assert [(c.name, c.type, c.nullable) for c in a.columns] == [
        ("id", "INTEGER", False),
        ("b_id", "INTEGER", False),
        ("amount", "NUMERIC(12,2)", True),
    ]
    assert sorted(t.name for t in sam.ordered(tables)) == ["a", "b"]  # cycle terminates


