@pytest.mark.skipif(shutil.which("docker") is None, reason="needs Docker for a real Postgres")
def test_postgres_schema_applies_on_a_real_postgres(tmp_path):
    import subprocess
    import time

    built = brief_mod.build(
        "showcase", "x", automations=[_sample()], source=REF, repo_root=ROOT, db_engine="postgres"
    )
    ddl = brief_mod.schema(built, ROOT)
    ddl += "INSERT INTO category (code, name) VALUES ('A', 'a');\n"  # id left to the database
    ddl += "SELECT count(*) FROM category;\n"
    name = f"twinlab-test-pg-{os.getpid()}"
    subprocess.run(["docker", "rm", "-f", name], capture_output=True)
    started = subprocess.run(
        [
            "docker",
            "run",
            "-d",
            "--name",
            name,
            "-e",
            "POSTGRES_PASSWORD=test",
            "postgres:17-alpine",
        ],
        capture_output=True,
        text=True,
    )
    if started.returncode != 0:
        pytest.skip(f"cannot start postgres: {started.stderr[:200]}")
    try:
        # Wait over TCP: while the image initialises it runs a temporary server on the Unix
        # socket only, then restarts, so a socket check can pass just before the restart.
        for _ in range(90):
            ready = subprocess.run(
                ["docker", "exec", name, "pg_isready", "-h", "127.0.0.1", "-U", "postgres"],
                capture_output=True,
            )
            if ready.returncode == 0:
                break
            time.sleep(1)
        else:
            pytest.fail("postgres did not accept TCP connections within 90 s")
        out = subprocess.run(
            [
                "docker",
                "exec",
                "-i",
                name,
                "psql",
                "-h",
                "127.0.0.1",
                "-U",
                "postgres",
                "-v",
                "ON_ERROR_STOP=1",
                "-tA",
            ],
            input=ddl,
            capture_output=True,
            text=True,
        )
        assert out.returncode == 0, out.stderr
        assert out.stdout.strip().splitlines()[-1] == "1"
    finally:
        subprocess.run(["docker", "rm", "-f", name], capture_output=True)


