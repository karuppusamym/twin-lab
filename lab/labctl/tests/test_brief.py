def _repo(tmp_path):
    for folder in ("automations/uipath-case-update", "apps", "lab"):
        (tmp_path / folder).mkdir(parents=True)
    shutil.copy(SAMPLE, tmp_path / "automations/uipath-case-update/automation.yaml")
    return tmp_path


def test_brief_command_writes_files_and_will_not_overwrite_without_force(tmp_path, monkeypatch):
    root = _repo(tmp_path)
    monkeypatch.setenv("LABCTL_ROOT", str(root))
    args = ["brief", "showcase", "--source", str(REF), "--system", "Case Workbench"]
    result = runner.invoke(app, args)
    assert result.exit_code == 0, result.output
    assert "7 table(s) in scope" in result.output
    out = root / "apps/showcase"
    assert (out / "BRIEF.md").read_text(encoding="utf-8").startswith("# Build brief: showcase")
    assert "CREATE TABLE cases" in (out / "db/schema.sql").read_text(encoding="utf-8")
    App.model_validate(yaml.safe_load((out / "app.yaml").read_text(encoding="utf-8")))

    (out / "app.yaml").write_text("id: showcase  # edited by a person\n", encoding="utf-8")
    assert runner.invoke(app, args).exit_code == 1
    assert runner.invoke(app, [*args, "--force"]).exit_code == 0
    assert "edited by a person" in (out / "app.yaml").read_text(encoding="utf-8")


def test_brief_command_refuses_an_unknown_engine(tmp_path, monkeypatch):
    monkeypatch.setenv("LABCTL_ROOT", str(_repo(tmp_path)))
