def test_static_schema_matches_sqlalchemy_metadata():
    from app.models import Base  # the reference app, imported here only to check the parser

    parsed = {t.name: t for t in fastapi_app.analyse(REF).tables}
    assert set(parsed) == set(Base.metadata.tables)
    for name, table in Base.metadata.tables.items():
        mine = {c.name: c for c in parsed[name].columns}
        assert set(mine) == set(table.columns.keys()), name
        for column in table.columns:
            assert mine[column.name].nullable == column.nullable, f"{name}.{column.name}"
            assert mine[column.name].primary_key == column.primary_key
            fks = [(fk.column.table.name, fk.column.name) for fk in column.foreign_keys]
            assert ([mine[column.name].references] if mine[column.name].references else []) == fks


